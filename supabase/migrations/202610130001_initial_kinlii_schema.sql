create table public.profiles (
  id uuid primary key references auth.users (id) on delete cascade,
  display_name text not null default '',
  university_name text not null default '',
  email_domain text not null default '',
  bio text not null default '',
  avatar_url text,
  accessibility_preferences jsonb not null default '{}'::jsonb,
  created_at timestamptz not null default now(),
  updated_at timestamptz not null default now()
);

create table public.interests (
  id bigint generated by default as identity primary key,
  slug text not null unique,
  name text not null unique,
  description text not null default '',
  icon_name text not null default 'sparkles',
  active boolean not null default true
);

create table public.profile_interests (
  profile_id uuid not null references public.profiles (id) on delete cascade,
  interest_id bigint not null references public.interests (id) on delete cascade,
  created_at timestamptz not null default now(),
  primary key (profile_id, interest_id)
);

create table public.events (
  id uuid primary key default gen_random_uuid(),
  host_id uuid not null references public.profiles (id) on delete restrict,
  title text not null check (char_length(title) between 3 and 100),
  description text not null default '',
  category text not null,
  starts_at timestamptz not null,
  ends_at timestamptz,
  location_name text not null,
  latitude double precision,
  longitude double precision,
  capacity integer not null check (capacity between 2 and 12),
  status text not null default 'active' check (status in ('draft', 'active', 'cancelled', 'completed')),
  tags text[] not null default '{}',
  created_at timestamptz not null default now(),
  updated_at timestamptz not null default now(),
  constraint valid_event_time check (ends_at is null or ends_at > starts_at)
);

create table public.event_members (
  event_id uuid not null references public.events (id) on delete cascade,
  user_id uuid not null references public.profiles (id) on delete cascade,
  status text not null default 'confirmed' check (status in ('confirmed', 'left', 'cancelled')),
  joined_at timestamptz not null default now(),
  left_at timestamptz,
  primary key (event_id, user_id)
);

create table public.event_leave_records (
  id bigint generated by default as identity primary key,
  event_id uuid not null references public.events (id) on delete cascade,
  user_id uuid not null references public.profiles (id) on delete cascade,
  reason text not null check (char_length(reason) between 1 and 200),
  created_at timestamptz not null default now()
);

create table public.saved_events (
  user_id uuid not null references public.profiles (id) on delete cascade,
  event_id uuid not null references public.events (id) on delete cascade,
  created_at timestamptz not null default now(),
  primary key (user_id, event_id)
);

create table public.carpool_requests (
  id uuid primary key default gen_random_uuid(),
  event_id uuid not null references public.events (id) on delete cascade,
  user_id uuid not null references public.profiles (id) on delete cascade,
  public_pickup_location text not null,
  status text not null default 'requested' check (status in ('requested', 'matched', 'cancelled')),
  created_at timestamptz not null default now(),
  updated_at timestamptz not null default now(),
  unique (event_id, user_id)
);

create table public.notifications (
  id uuid primary key default gen_random_uuid(),
  user_id uuid not null references public.profiles (id) on delete cascade,
  type text not null,
  title text not null,
  body text not null,
  event_id uuid references public.events (id) on delete cascade,
  read_at timestamptz,
  created_at timestamptz not null default now()
);

