create or replace function public.handle_new_user()
returns trigger
language plpgsql
security definer
set search_path = public
as $$
begin
  insert into public.profiles (id, display_name, university_name, email_domain)
  values (
    new.id,
    coalesce(new.raw_user_meta_data ->> 'display_name', split_part(coalesce(new.email, ''), '@', 1)),
    coalesce(new.raw_user_meta_data ->> 'university_name', ''),
    lower(split_part(coalesce(new.email, ''), '@', 2))
  );
  return new;
end;
$$;

create trigger on_auth_user_created
after insert on auth.users
for each row execute function public.handle_new_user();

create or replace view public.event_feed
with (security_invoker = true)
as
select
  event.id,
  event.host_id,
  host.display_name as host_name,
  event.title,
  event.description,
  event.category,
  event.starts_at,
  event.ends_at,
  event.location_name,
  event.latitude,
  event.longitude,
  event.capacity,
  event.tags,
  count(member.user_id) filter (where member.status = 'confirmed')::integer as attendee_count,
  (event.capacity - count(member.user_id) filter (where member.status = 'confirmed'))::integer as spots_remaining
from public.events as event
join public.profiles as host on host.id = event.host_id
left join public.event_members as member on member.event_id = event.id
where event.status = 'active' and event.starts_at > now()
group by event.id, host.display_name
having count(member.user_id) filter (where member.status = 'confirmed') < event.capacity;

create or replace function public.join_event(p_event_id uuid)
returns table (event_id uuid, attendee_count integer, spots_remaining integer)
language plpgsql
security definer
set search_path = public
as $$
declare
  current_user_id uuid := auth.uid();
  event_capacity integer;
  confirmed_count integer;
begin
  if current_user_id is null then
    raise exception 'Authentication required';
  end if;

  select capacity into event_capacity
  from public.events
  where id = p_event_id and status = 'active' and starts_at > now()
  for update;

  if event_capacity is null then
    raise exception 'Event is unavailable';
  end if;

  if exists (
    select 1 from public.event_members
    where event_members.event_id = p_event_id
      and user_id = current_user_id
      and status = 'confirmed'
  ) then
    select count(*)::integer into confirmed_count
    from public.event_members
    where event_members.event_id = p_event_id and status = 'confirmed';
    return query select p_event_id, confirmed_count, event_capacity - confirmed_count;
    return;
  end if;

  select count(*)::integer into confirmed_count
  from public.event_members
  where event_members.event_id = p_event_id and status = 'confirmed';

  if confirmed_count >= event_capacity then
    raise exception 'Event is full';
  end if;

  insert into public.event_members (event_id, user_id, status, joined_at, left_at)
  values (p_event_id, current_user_id, 'confirmed', now(), null)
  on conflict (event_id, user_id) do update
  set status = 'confirmed', joined_at = now(), left_at = null;

  confirmed_count := confirmed_count + 1;
  return query select p_event_id, confirmed_count, event_capacity - confirmed_count;
end;
$$;

create or replace function public.leave_event(p_event_id uuid, p_reason text)
returns table (event_id uuid, attendee_count integer, spots_remaining integer)
language plpgsql
security definer
set search_path = public
as $$
declare
  current_user_id uuid := auth.uid();
  event_capacity integer;
  confirmed_count integer;
  cleaned_reason text := btrim(p_reason);
begin
  if current_user_id is null then
    raise exception 'Authentication required';
  end if;
  if cleaned_reason = '' or char_length(cleaned_reason) > 200 then
    raise exception 'A leave reason between 1 and 200 characters is required';
  end if;

  select capacity into event_capacity
  from public.events
  where id = p_event_id
  for update;

  if event_capacity is null then
    raise exception 'Event not found';
  end if;

  update public.event_members
  set status = 'left', left_at = now()
  where event_members.event_id = p_event_id
    and user_id = current_user_id
    and status = 'confirmed';

  if not found then
    raise exception 'You are not currently attending this event';
  end if;

  insert into public.event_leave_records (event_id, user_id, reason)
  values (p_event_id, current_user_id, cleaned_reason);

  select count(*)::integer into confirmed_count
  from public.event_members
  where event_members.event_id = p_event_id and status = 'confirmed';

  return query select p_event_id, confirmed_count, event_capacity - confirmed_count;
end;
$$;

